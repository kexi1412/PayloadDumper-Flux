'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const zlib = require('node:zlib');
const root = path.resolve(__dirname, '..');
const pkg = require('../package.json');
const config = require('../src-tauri/tauri.conf.json');
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const cap = 10_000_000; // Strict decimal MB, not the looser 10 MiB threshold.
const candidates = [path.join(root, 'src-tauri/target/x86_64-pc-windows-msvc/release'), path.join(root, 'src-tauri/target/release')];
const release = candidates.find(p => fs.existsSync(path.join(p, 'payload-dumper-flux.exe')));
assert(release, 'Build the native release first.');
assert.equal(config.version, pkg.version);
assert.equal(config.bundle.windows.webviewInstallMode.type, 'skip', 'Do not hide a bundled or downloaded browser behind a small bootstrapper.');
assert(!(config.bundle.externalBin || []).length, 'The extraction engine must be in-process, not a bundled JVM sidecar.');
assert(!pkg.devDependencies?.electron && !pkg.devDependencies?.['electron-builder']);
const nsis = path.join(release, 'bundle/nsis');
const installers = fs.readdirSync(nsis).filter(n => n.endsWith('-setup.exe') && n.includes(pkg.version));
assert.equal(installers.length, 1, `Expected one versioned installer: ${installers}`);
const sourceInstaller = path.join(nsis, installers[0]);
const installerData = fs.readFileSync(sourceInstaller);
assert(installerData.subarray(0, 2).toString() === 'MZ');
assert(installerData.length < cap, `Installer ${installerData.length} bytes must be below ${cap}.`);
const executable = path.join(release, 'payload-dumper-flux.exe');
const exeData = fs.readFileSync(executable);
assert(exeData.subarray(0, 2).toString() === 'MZ');
const out = path.join(root, 'release');
fs.mkdirSync(out, { recursive: true });
const installerName = `PayloadDumper-Flux-PC-${pkg.version}-x64-setup.exe`;
const installer = path.join(out, installerName);
fs.writeFileSync(installer, installerData);
const crcTable = Array.from({ length: 256 }, (_, n) => { for (let i = 0; i < 8; i++) n = (n & 1) ? 0xedb88320 ^ (n >>> 1) : n >>> 1; return n >>> 0; });
function crc32(bytes) { let n = 0xffffffff; for (const b of bytes) n = crcTable[(n ^ b) & 255] ^ (n >>> 8); return (n ^ 0xffffffff) >>> 0; }
const entries = [{ name: 'payload-dumper-flux.exe', data: exeData }, { name: 'LICENSE.txt', data: fs.readFileSync(path.join(root, '../LICENSE')) }];
const loader = path.join(release, 'WebView2Loader.dll');
if (fs.existsSync(loader)) entries.push({ name: 'WebView2Loader.dll', data: fs.readFileSync(loader) });
const bodies = [], directory = [];
let offset = 0;
for (const { name, data } of entries) {
  const filename = Buffer.from(name), compressed = zlib.deflateRawSync(data, { level: 9 });
  assert.equal(sha(zlib.inflateRawSync(compressed)), sha(data));
  const crc = crc32(data), local = Buffer.alloc(30), central = Buffer.alloc(46);
  local.writeUInt32LE(0x04034b50); local.writeUInt16LE(20, 4); local.writeUInt16LE(0x800, 6); local.writeUInt16LE(8, 8);
  local.writeUInt32LE(crc, 14); local.writeUInt32LE(compressed.length, 18); local.writeUInt32LE(data.length, 22); local.writeUInt16LE(filename.length, 26);
  central.writeUInt32LE(0x02014b50); central.writeUInt16LE(20, 4); central.writeUInt16LE(20, 6); central.writeUInt16LE(0x800, 8); central.writeUInt16LE(8, 10);
  central.writeUInt32LE(crc, 16); central.writeUInt32LE(compressed.length, 20); central.writeUInt32LE(data.length, 24); central.writeUInt16LE(filename.length, 28); central.writeUInt32LE(offset, 42);
  bodies.push(local, filename, compressed); directory.push(central, filename); offset += local.length + filename.length + compressed.length;
}
const cd = Buffer.concat(directory), end = Buffer.alloc(22);
end.writeUInt32LE(0x06054b50); end.writeUInt16LE(entries.length, 8); end.writeUInt16LE(entries.length, 10); end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16);
const portableData = Buffer.concat([...bodies, cd, end]);
assert(portableData.length < cap, `Portable ZIP ${portableData.length} bytes must be below ${cap}.`);
const portableName = `PayloadDumper-Flux-PC-${pkg.version}-x64-portable.zip`;
fs.writeFileSync(path.join(out, portableName), portableData);
const records = [{ name: installerName, bytes: installerData.length, sha256: sha(installerData) }, { name: portableName, bytes: portableData.length, sha256: sha(portableData) }];
const manifest = { version: pkg.version, framework: 'Tauri + native Rust firmware engine', systemDependency: 'Windows system WebView2 runtime', byteLimit: cap, installedExecutableBytes: exeData.length, executableSHA256: sha(exeData), portableEntries: entries.map(e => e.name), files: records };
fs.writeFileSync(path.join(out, 'native-package.json'), JSON.stringify(manifest, null, 2) + '\n');
fs.writeFileSync(path.join(out, 'SHA256SUMS-native.txt'), records.map(r => `${r.sha256}  ${r.name}`).join('\n') + '\n');
fs.writeFileSync(path.join(out, 'native-release-notes.md'), `# PC ${pkg.version}\n\nNative Windows x64 build; the existing workbench now uses system WebView2 and an in-process Rust extraction engine. No Chromium, Node.js or Java runtime is bundled or downloaded by the installer.\n\n- Installer: ${(installerData.length / 1_000_000).toFixed(2)} MB (${installerData.length} bytes).\n- Portable ZIP: ${(portableData.length / 1_000_000).toFixed(2)} MB (${portableData.length} bytes).\n- Uses the system WebView2 runtime available on supported Windows 10/11 systems.\n- Supports operation-based full payload extraction, local/HTTP firmware, hash checks and identity-bound resume.\n\nSHA-256 checksums are attached.\n`);
console.log(JSON.stringify(manifest, null, 2));
console.log(`NATIVE_EXECUTABLE=${executable}`);
console.log(`NATIVE_INSTALLER=${installer}`);
